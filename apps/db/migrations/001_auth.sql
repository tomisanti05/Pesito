-- Contraseña hasheada (bcrypt) en Usuarios.
-- Nullable para no romper usuarios existentes: podrán registrarse
-- de nuevo o recibir una contraseña por un flujo administrativo.
ALTER TABLE "Usuarios"
  ADD COLUMN IF NOT EXISTS password_hash varchar(255);

-- Tokens de recuperación de contraseña.
-- Se guarda SOLO el hash SHA-256 del token, nunca el token crudo.
CREATE TABLE IF NOT EXISTS "PasswordResetToken" (
  "id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "idUsuario"  integer NOT NULL REFERENCES "Usuarios" ("id") ON DELETE CASCADE,
  "tokenHash"  varchar(64) NOT NULL UNIQUE,
  "expiresAt"  timestamptz NOT NULL,
  "usedAt"     timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_reset_usuario
  ON "PasswordResetToken" ("idUsuario");

CREATE INDEX IF NOT EXISTS idx_reset_expira
  ON "PasswordResetToken" ("expiresAt");
